/* Character used to draw each of the 9 states. */
char state_glyph[] = " 01./:;|\\";

char *cells;

int main(int argc, char *argv[]) {
  int left, middle, right, cell, generation, limit, width = 19;

  limit = atoi(argv[1]);
  cells = (char *)calloc(80 + limit, 1);
  cells[0] = 1;

  printf("       ");
  for (generation = 1; generation <= limit; generation++) {
    /* widen the drawn region once the sieve signal reaches the edge */
    if (generation > 30 && cells[width - 2] + cells[width - 1] != 0)
      width++;

    /* print the current row, preceded by one blank column */
    printf("%c", state_glyph[0]);
    for (cell = 0; cell < width; cell++)
      printf("%c", state_glyph[(int)cells[cell]]);

    /* compute the next row in place; the old left value is remembered */
    left = 0;
    for (cell = 0; cell < width; cell++) {
      middle = cells[cell];
      right = cells[cell + 1];
      cells[cell] = next_state[left][middle][right];
      left = middle;
    }

    /* the leftmost cell leaves state 1 (drawn as 0) when the number is prime;
       label the next row with the number in that case */
    if (cells[0] != 1)
      printf("\n%6i ", generation);
    else
      printf("\n       ");
  }
}
